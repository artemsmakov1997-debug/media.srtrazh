"""Morphological trigger lexicon: one entry → every inflected form and combination.

Each word is written once with its declension class. The module expands it into
all cases and numbers, ё/е spellings, hyphen/space variants of compounds and
"modifier × head" combinations. Groups become ordinary ``Rule`` objects and run
in the same engine as ``rules.py`` (Python on the server and Pyodide in the
browser). Existing hand-written rules are compiled first, so where both match
the same fragment in the same category the more specific old rule wins.

Scope of a group:
- ``lexicon_any``    — the word is loaded in itself (хунта, рашист, укронацист);
- ``lexicon_public`` — the word also has an everyday literal sense (враг, убийца,
  террорист, укроп), so it needs a public/political subject nearby.
An optional ``guard`` excludes obvious homonyms (orca, Tolkien, WWII history).

A match is a review candidate, not a proven manipulation; status (author text,
quotation, negation) is assigned by the common engine.
"""


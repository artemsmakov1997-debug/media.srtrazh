# ---------------------------------------------------------------- morphology
ADJ = (r"(?:ый|ий|ой|ая|яя|ое|ее|ые|ие|ого|его|ому|ему|ым|им|ом|ем|ую|юю|ых|их|ыми|ими|ою|ею)")
CLASSES = {
    # враг, рашист, террорист: враг/врага/врагу/врагом/враге/враги/врагов…
    "m": r"(?:а|у|ом|ем|е|ы|и|ов|ев|ей|ам|ами|ах)?",
    # каратель, москаль, концлагерь
    "m_soft": r"(?:ь|я|ю|ем|ём|е|и|ей|ям|ями|ях)",
    # бандеровец → бандеровца, бандеровцы
    "m_ets": r"(?:ец|ца|цу|цом|цем|це|цы|цев|цам|цами|цах)",
    # выродок → выродка, застенок → застенки
    "m_ok": r"(?:ок|ка|ку|ком|ке|ки|ков|кам|ками|ках)",
    # хунта, банда (without the empty genitive plural: «клик» ≠ «клика»)
    "f": r"(?:а|ы|и|е|у|ой|ою|ам|ами|ах)",
    # русня, Эрэфия
    "f_ya": r"(?:я|и|е|ю|ей|ею|ям|ями|ях)",
    # мразь, тварь, нечисть, власть
    "f_soft": r"(?:ь|и|ью|ей|ям|ями|ях)",
    # государство, правительство
    "n": r"(?:о|а|у|ом|е|ам|ами|ах)?",
    # пыточная, бандеровский, людоедский
    "adj": ADJ,
}
LETTER = r"а-яёa-z0-9"
B = rf"(?<![{LETTER}])"
E = rf"(?![{LETTER}])"
HY = r"[-‑–\s]?"


def _yo(value):
    return value.replace("ё", "[её]").replace("Ё", "[ЕЁ]")


def form(stem, cls="m"):
    """All forms of one lexeme, without word boundaries."""
    if cls == "raw":
        return f"(?:{stem})"
    return f"(?:{_yo(stem).replace('-', HY)}{CLASSES[cls]})"


def words(*items):
    """Bounded alternation of lexemes: ("враг", "m") or ("…regex…", "raw")."""
    return B + "(?:" + "|".join(form(*item) if isinstance(item, tuple) else form(item) for item in items) + ")" + E


def compound(prefixes, roots):
    """укро + нацист → укронацист, укро-нацист, укро нацист; рус + фашист → русофашист."""
    head = "(?:" + "|".join(_yo(prefix) for prefix in prefixes) + ")о?"   # рус-о-фашист
    return B + head + HY + "(?:" + "|".join(form(*root) for root in roots) + ")" + E


def combo(modifiers, heads, gap=1):
    """{кровав, преступн} × {режим, хунта}; up to ``gap`` words in between."""
    mods = "(?:" + "|".join(_yo(mod) for mod in modifiers) + ")" + ADJ
    return (B + mods + r"\s+(?:[а-яё-]+\s+){0," + str(gap) + "}" +
            "(?:" + "|".join(form(*head) for head in heads) + ")" + E)


def joined(*patterns):
    return "|".join(f"(?:{pattern})" for pattern in patterns)


